#!/usr/bin/env python3
"""Guard the source config defaults so a credential or forced expert route never
lands in the public repo. Runtime routing (e.g. an OmniRoute combo via Supervisor
options) is a per-install setting and must not be baked into config.yaml.

Also guards llm_base_url: it must have an empty default in options (so it
shows in the Configuration tab) and a non-optional `str` schema type matching
that default. An optional (`str?`) key with a default contradicts HA's rules.

Finally it guards the Ponytail rung-1 removals: the dead remote-code installer
(ha_autoapps.sh + its Dockerfile wiring), the dead `ingress` option/schema key,
the unused `embedded-db` pip extra, and the dead `bashio::*` functions in the
standalone shim. The checks fail if any of them returns, and also verify the
behaviour that replaced them (top-level ingress, the local-llm/local-onnx
extras and the shebang probe) stays intact.

It also guards the release metadata: versions.json, both pins in the
Dockerfile, the add-on version and the consolidation-incident troubleshooting
sections in README/DOCS must agree.

No third-party deps: parses the small options/schema blocks with string checks
and exercises the shim with stdlib subprocesses.
"""

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CFG = REPO / "hindsight" / "config.yaml"
DOCKERFILE = REPO / "hindsight" / "Dockerfile"
AUTOAPPS = REPO / "hindsight" / "ha_autoapps.sh"
SHIM = REPO / "hindsight" / "bashio-standalone.sh"
ENTRYPOINT = REPO / "hindsight" / "ha_entrypoint.sh"

# Functions called by the add-on's own runtime scripts: rootfs/etc/cont-init.d,
# rootfs/etc/services.d and ha_entrypoint.sh (including the shebang probe and
# the exit.ok/exit.nok sed rewrites in run_one_script).
OWN_RUNTIME_FUNCTIONS = {
    "bashio::app.ingress_port",
    "bashio::app.ip_address",
    "bashio::app.version",
    "bashio::config",
    "bashio::exit.nok",
    "bashio::exit.ok",
    "bashio::log.error",
    "bashio::log.fatal",
    "bashio::log.info",
    "bashio::log.warning",
}

# ha_automodules.sh:10 downloads these four templates from
# alexbelgium/hassio-addons master/.templates at build time, in addition to the
# MODULES passed by the Dockerfile. Audited 2026-11-26: every bashio::* call in
# them is listed here. Supervisor-only branches count too -- 00-banner.sh copies
# the shim to /usr/bin/bashio in standalone mode, so it can be the bashio that a
# later script sees. Keep this snapshot in sync when the templates change.
TEMPLATE_FUNCTIONS = {
    # 00-banner.sh
    "bashio::supervisor.ping",
    "bashio::log.blue",
    "bashio::app.name",
    "bashio::app.description",
    "bashio::app.version",
    "bashio::var.true",
    "bashio::app.update_available",
    "bashio::app.version_latest",
    "bashio::log.magenta",
    "bashio::log.green",
    "bashio::info.operating_system",
    "bashio::info.arch",
    "bashio::info.machine",
    "bashio::info.homeassistant",
    "bashio::info.supervisor",
    "bashio::config.has_value",
    "bashio::config",
    # 01-custom_script.sh
    "bashio::log.notice",
    # 01-config_yaml.sh
    "bashio::log.red",
    "bashio::app.option",
    "bashio::log.yellow",
    "bashio::config.false",
    # 00-global_var.sh
    "bashio::api.supervisor",
}

REACHABLE_FUNCTIONS = OWN_RUNTIME_FUNCTIONS | TEMPLATE_FUNCTIONS


def run_shim(body, extra_env=None, timeout=15):
    """Source the shim in a clean bash and run ``body``; return CompletedProcess."""
    env = os.environ.copy()
    for name in (
        "STANDALONE_FORCE_SUPERVISOR_PING",
        "BUILD_VERSION",
        "ADDON_IP_ADDRESS",
        "ADDON_INGRESS_PORT",
        "CFG_MODE",
    ):
        env.pop(name, None)
    if extra_env:
        env.update(extra_env)
    return subprocess.run(
        ["bash", "-c", 'set -u; . "$1"; ' + body, "_", str(SHIM)],
        capture_output=True,
        text=True,
        env=env,
        timeout=timeout,
    )


def check_bashio_shim(errors):
    """Guard the reachable-function set and the two untested startup paths."""
    if not SHIM.is_file():
        errors.append("hindsight/bashio-standalone.sh is missing")
        return
    shim = SHIM.read_text()

    syntax = subprocess.run(["bash", "-n", str(SHIM)], capture_output=True, text=True)
    if syntax.returncode != 0:
        errors.append(f"bashio-standalone.sh fails bash -n: {syntax.stderr.strip()}")

    defined = {
        "bashio::" + name for name in re.findall(r"^bashio::([A-Za-z0-9_.]+)\(\)", shim, re.M)
    }
    dead = sorted(defined - REACHABLE_FUNCTIONS)
    missing = sorted(REACHABLE_FUNCTIONS - defined)
    if dead:
        errors.append("dead bashio functions still defined: " + ", ".join(dead))
    if missing:
        errors.append("reachable bashio functions missing: " + ", ".join(missing))
    # The pre-v0.18 aliases are generated by eval, so the regex above cannot see
    # them; guard the generator itself as well.
    if "bashio::addon." in shim:
        errors.append("dead bashio::addon.* alias loop is still present")

    # Functional smoke checks for the functions with no dedicated suite. An
    # empty value or a wrong exit status here is what breaks the shebang probe
    # and the Supervisor wait in ha_entrypoint.sh.
    cases = (
        (
            "app.version from BUILD_VERSION",
            "bashio::app.version",
            {"BUILD_VERSION": "2.3.4"},
            lambda r: r.returncode == 0 and r.stdout == "2.3.4",
            "2.3.4",
        ),
        (
            "app.ip_address from ADDON_IP_ADDRESS",
            "bashio::app.ip_address",
            {"ADDON_IP_ADDRESS": "172.30.0.2"},
            lambda r: r.returncode == 0 and r.stdout == "172.30.0.2",
            "172.30.0.2",
        ),
        (
            "app.ingress_port from ADDON_INGRESS_PORT",
            "bashio::app.ingress_port",
            {"ADDON_INGRESS_PORT": "9997"},
            lambda r: r.returncode == 0 and r.stdout == "9997",
            "9997",
        ),
        (
            "config reads a prefixed env key",
            "bashio::config mode",
            {"CFG_MODE": "advanced"},
            lambda r: r.returncode == 0 and r.stdout == "advanced",
            "advanced",
        ),
        (
            "log.info prints its message",
            "bashio::log.info 'hello shim'",
            None,
            lambda r: r.returncode == 0 and "hello shim" in r.stdout,
            "hello shim",
        ),
        (
            "supervisor.ping fails without a Supervisor",
            "bashio::supervisor.ping || exit 0; exit 1",
            None,
            lambda r: r.returncode == 0,
            "failure",
        ),
        (
            "var.true accepts a true value",
            "bashio::var.true TRUE",
            None,
            lambda r: r.returncode == 0,
            "true",
        ),
        (
            "exit.nok exits 1 with a message",
            'bashio::exit.nok "boom"',
            None,
            lambda r: r.returncode == 1 and "boom" in r.stdout + r.stderr,
            "boom",
        ),
    )
    for name, body, env, ok, expected in cases:
        result = run_shim(body, env)
        if not ok(result):
            errors.append(
                f"shim {name}: expected {expected!r}, got rc={result.returncode} "
                f"stdout={result.stdout!r} stderr={result.stderr!r}"
            )

    # Run the *real* probe script from ha_entrypoint.sh, with only its hardcoded
    # library paths redirected to the shim under test. This is the startup path
    # that has no test of its own.
    if not ENTRYPOINT.is_file():
        errors.append("hindsight/ha_entrypoint.sh is missing")
        return
    match = re.search(r"probe_script_content='\n(.*?)\n'\n", ENTRYPOINT.read_text(), re.S)
    if not match:
        errors.append("could not extract probe_script_content from ha_entrypoint.sh")
        return
    with tempfile.TemporaryDirectory() as td:
        absent = str(Path(td) / "absent")
        probe = match.group(1)
        for path in (
            "/usr/lib/bashio/bashio.sh",
            "/usr/lib/bashio/lib.sh",
            "/usr/src/bashio/bashio.sh",
            "/usr/local/lib/bashio/bashio.sh",
            "/.bashio-standalone.sh",
        ):
            probe = probe.replace(path, absent)
        probe = probe.replace("/usr/local/lib/bashio-standalone.sh", str(SHIM))

        env = os.environ.copy()
        env["BUILD_VERSION"] = "9.8.7"
        result = subprocess.run(
            ["bash", "-c", probe],
            capture_output=True,
            text=True,
            env=env,
            timeout=15,
        )
        if result.returncode != 0 or result.stdout.strip() != "9.8.7":
            errors.append(
                "shebang probe did not resolve bashio::app.version through the shim: "
                f"rc={result.returncode} stdout={result.stdout!r} stderr={result.stderr!r}"
            )


VERSIONS = REPO / "hindsight" / "versions.json"
README = REPO / "README.md"
DOCS = REPO / "hindsight" / "DOCS.md"


def main() -> int:
    errors = []
    text = CFG.read_text()
    options = text.split("options:", 1)[1].split("schema:", 1)[0] if "options:" in text else ""
    schema = text.split("schema:", 1)[1] if "schema:" in text else ""

    def opt(name):
        for line in options.splitlines():
            line = line.strip()
            if line.startswith(f"{name}:"):
                return line.split(":", 1)[1].strip().strip('"').strip("'")
        return None

    def schema_type(name):
        for line in schema.splitlines():
            line = line.strip()
            if line.startswith(f"{name}:"):
                return line.split(":", 1)[1].strip().strip('"').strip("'")
        return None

    key = opt("llm_api_key") or ""
    if key and key != '""':
        errors.append(f"llm_api_key must be empty in source config, got {key[:8]}...")

    if opt("mode") != "simple":
        errors.append(f"mode must default to 'simple' for a no-key install, got {opt('mode')!r}")
    if opt("llm_provider") != "llamacpp":
        errors.append(f"llm_provider must default to local 'llamacpp', got {opt('llm_provider')!r}")

    # llm_base_url must be a UI-visible, empty-by-default option. A `str?`
    # schema type with a default contradicts Home Assistant's option/schema rules.
    base_url = opt("llm_base_url")
    if base_url is None:
        errors.append("llm_base_url must be present in options so it appears in the UI")
    elif base_url != "":
        errors.append(f"llm_base_url default must be empty in source config, got {base_url[:40]!r}")
    url_type = schema_type("llm_base_url")
    if url_type != "str":
        errors.append(f"llm_base_url schema must be 'str' (it has a default), got {url_type!r}")

    # Dedicated consolidation-LLM route (1.2.26): four expert-mode options with
    # EMPTY defaults. Unset means "reuse the normal LLM settings", so the source
    # config must carry no credential and no forced consolidation route. The
    # schema types mirror the main LLM options: str for free-text values and
    # password for the key (both non-optional because they have a "" default).
    consolidation_schema = {
        "consolidation_llm_provider": "str",
        "consolidation_llm_model": "str",
        "consolidation_llm_base_url": "str",
        "consolidation_llm_api_key": "password",
    }
    for name, expected_type in consolidation_schema.items():
        value = opt(name)
        if value is None:
            errors.append(f"{name} must be present in options so it appears in the UI")
        elif value != "":
            errors.append(f"{name} default must be empty in source config, got {value[:40]!r}")
        actual_type = schema_type(name)
        if actual_type != expected_type:
            errors.append(f"{name} schema must be '{expected_type}', got {actual_type!r}")

    # No credential-looking token anywhere in the source config.
    if "sk-" in text:
        errors.append("source config contains an 'sk-' token (possible credential leak)")

    # Version must be a quoted string.
    for line in text.splitlines():
        if line.startswith("version:"):
            v = line.split(":", 1)[1].strip()
            if not (v.startswith('"') and v.endswith('"')):
                errors.append("version must be a quoted string")
            break

    # Ponytail rung 1: the dead installer downloaded and eval'd a remote script
    # for an empty package list. Neither it nor its Dockerfile wiring may stay.
    if AUTOAPPS.exists():
        errors.append("hindsight/ha_autoapps.sh must be deleted (dead remote installer)")
    docker = DOCKERFILE.read_text() if DOCKERFILE.is_file() else ""
    if not docker:
        errors.append("hindsight/Dockerfile is missing")
    for token in ("ha_autoapps", "ha_automatic_packages", "PACKAGES"):
        if token in docker:
            errors.append(f"Dockerfile still references {token!r}")

    # Ingress is forced by the top-level keys and the control-plane service;
    # the unused options/schema toggle must not reappear as a dead UI control.
    for block_name, block in (("options", options), ("schema", schema)):
        for line in block.splitlines():
            if line.strip().startswith("ingress:"):
                errors.append(f"config.yaml {block_name} still defines {line.strip()!r}")
    top_level = {}
    for line in text.splitlines():
        if line and not line[0].isspace() and ":" in line:
            key_name, value = line.split(":", 1)
            top_level[key_name.strip()] = value.strip()
    for key_name, expected in (
        ("ingress", "true"),
        ("ingress_port", "9997"),
        ("ingress_entry", "dashboard"),
    ):
        if top_level.get(key_name) != expected:
            errors.append(
                f"top-level {key_name} must stay {expected!r}, got {top_level.get(key_name)!r}"
            )

    # embedded-db (pg0) is never used: 30-config.sh hardcodes the PostgreSQL 15
    # URL. Only the two local-model extras should be requested, at the same pin.
    if "embedded-db" in docker:
        errors.append("Dockerfile still mentions the unused 'embedded-db' extra")
    extras_line = next(
        (line.strip() for line in docker.splitlines() if "hindsight-api-slim[" in line),
        None,
    )
    if extras_line is None:
        errors.append("Dockerfile no longer pins hindsight-api-slim extras")
    elif not (
        extras_line.startswith('"hindsight-api-slim[local-llm,local-onnx]==')
        and extras_line.endswith('"')
    ):
        errors.append(
            f"hindsight-api-slim must pin [local-llm,local-onnx] extras, got {extras_line!r}"
        )
    if "postgresql-15" not in docker:
        errors.append("Dockerfile must keep installing PostgreSQL 15")

    check_bashio_shim(errors)
    # Release metadata: add-on 1.2.26 ships upstream 1.3.0 in both components.
    try:
        versions = json.loads(VERSIONS.read_text())
    except (OSError, ValueError) as exc:
        errors.append(f"hindsight/versions.json is not valid JSON: {exc}")
        versions = {}
    for component in ("hindsight_api", "control_plane"):
        value = versions.get(component)
        if value != "1.3.0":
            errors.append(f"versions.json {component} must be 1.3.0, got {value!r}")
    api_pin = re.search(r"hindsight-api-slim\[[^\]]+\]==([0-9.]+)", docker)
    cp_pin = re.search(r"hindsight-control-plane@([0-9.]+)", docker)
    if not api_pin or api_pin.group(1) != "1.3.0":
        errors.append(
            f"Dockerfile API pin must be 1.3.0, got {api_pin.group(1) if api_pin else None!r}"
        )
    if not cp_pin or cp_pin.group(1) != "1.3.0":
        errors.append(
            f"Dockerfile control-plane pin must be 1.3.0, got {cp_pin.group(1) if cp_pin else None!r}"
        )
    if top_level.get("version") != '"1.2.26"':
        errors.append(f"add-on version must be 1.2.26, got {top_level.get('version')!r}")

    # The consolidation backlog is handled at runtime, so the operational
    # guidance must ship in both docs with the real diagnostic endpoints.
    for name, doc in (("README.md", README), ("hindsight/DOCS.md", DOCS)):
        dtext = doc.read_text() if doc.is_file() else ""
        for token in (
            "consolidation_state=pending",
            "operations?type=consolidation",
            "llm-requests",
            "HINDSIGHT_API_LLM_MODEL",
            '{"updates":{',
        ):
            if token not in dtext:
                errors.append(f"{name} missing consolidation troubleshooting token {token!r}")
        if not re.search(r"(?is)\*\*(?:do not|never)\s+delete\s+pending\s+memories", dtext):
            errors.append(f"{name} must warn against deleting pending memories")

    if errors:
        for e in errors:
            print("FAIL:", e)
        return 1
    print(
        "source defaults OK: simple/llamacpp, empty api key and base URL, "
        "str base-URL schema, four empty consolidation options with matching "
        "schema, quoted version, no token, no dead installer/ingress option/"
        "embedded-db extra"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
